// Generates the Android launcher icon and the notification icon from the same
// fox mark the app and the Windows icon use (lib/brand_geometry.dart).
//
//   dart run tool/generate_android_icons.dart
//
// Writes, under android/app/src/main/:
//   res/drawable/ic_launcher_foreground.xml   adaptive icon foreground (mint mark, visor cut out)
//   res/drawable/ic_launcher_monochrome.xml   the same shape for Android 13+ themed icons
//   res/drawable/ic_stat_foxy.xml             status-bar icon of the VPN notification (white)
//   res/mipmap-anydpi-v26/ic_launcher.xml     adaptive icon (dark background colour + the layers above)
//   ic_launcher-playstore.png                 512 px store icon (the same rounded square as the .ico)
//
// minSdk is 26, so adaptive icons are available everywhere and no per-density
// PNG launcher icons are needed.

import 'dart:io';
import 'dart:math' as math;

import 'package:foxyvpn/brand_geometry.dart';
import 'package:image/image.dart' as img;

import 'generate_icon.dart' as base;

/// Mark box (x 0.14..0.86, y 0.12..0.90) centre, as in generate_icon.dart.
const _boxCenter = (0.50, 0.51);

/// Visor thickness as a fraction of the mark's unit square (generate_icon: 0.07 of
/// the icon, where the mark's unit square is 0.70 / 0.78 of the icon).
const _visorStrokeOfUnit = 0.07 * 0.78 / 0.70;

void main() {
  final root = File.fromUri(Platform.script).parent.parent;
  final main = '${root.path}/android/app/src/main';

  // Adaptive icon: 108 x 108 dp, the visible circle is about 72 dp, the safe zone 66 dp.
  final foreground = _vector(viewport: 108, markScale: 62);
  _write('$main/res/drawable/ic_launcher_foreground.xml', _drawable(108, '#FF3DDC97', foreground));
  _write('$main/res/drawable/ic_launcher_monochrome.xml', _drawable(108, '#FF000000', foreground));

  // Status bar icon, 24 dp.
  _write('$main/res/drawable/ic_stat_foxy.xml', _drawable(24, '#FFFFFFFF', _vector(viewport: 24, markScale: 21), size: 24));

  _write('$main/res/mipmap-anydpi-v26/ic_launcher.xml', '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''');

  final png = File('$main/ic_launcher-playstore.png');
  png.writeAsBytesSync(img.encodePng(base.render(512)));

  stdout.writeln('Wrote the Android icons under $main');
}

void _write(String path, String text) {
  final file = File(path);
  file.parent.createSync(recursive: true);
  file.writeAsStringSync(text);
}

String _n(double v) => v.toStringAsFixed(2).replaceFirst(RegExp(r'\.?0+$'), '');

/// Path data (even-odd): the rounded mark outline plus the visor as a stadium
/// shape that cuts a hole into it.
String _vector({required double viewport, required double markScale}) {
  final centre = viewport / 2;
  (double, double) place((double, double) p) =>
      (centre + (p.$1 - _boxCenter.$1) * markScale, centre + (p.$2 - _boxCenter.$2) * markScale);

  final points = [for (final p in foxMarkOutline) place(p)];
  final radius = foxMarkCornerRadius * markScale;
  final d = StringBuffer();
  for (var i = 0; i < points.length; i++) {
    final prev = points[(i + points.length - 1) % points.length];
    final cur = points[i];
    final next = points[(i + 1) % points.length];
    (double, double) toward((double, double) to) {
      final dx = to.$1 - cur.$1, dy = to.$2 - cur.$2;
      final len = math.sqrt(dx * dx + dy * dy);
      final r = radius < len / 2 ? radius : len / 2;
      return (cur.$1 + dx / len * r, cur.$2 + dy / len * r);
    }

    final start = toward(prev);
    final end = toward(next);
    d
      ..write(i == 0 ? 'M' : 'L')
      ..write('${_n(start.$1)},${_n(start.$2)}')
      ..write('Q${_n(cur.$1)},${_n(cur.$2)} ${_n(end.$1)},${_n(end.$2)}');
  }
  d.write('Z');

  final a = place(foxMarkVisor.$1);
  final b = place(foxMarkVisor.$2);
  final h = _visorStrokeOfUnit * markScale / 2;
  d
    ..write('M${_n(a.$1)},${_n(a.$2 - h)}')
    ..write('L${_n(b.$1)},${_n(b.$2 - h)}')
    ..write('A${_n(h)},${_n(h)} 0 0 1 ${_n(b.$1)},${_n(b.$2 + h)}')
    ..write('L${_n(a.$1)},${_n(a.$2 + h)}')
    ..write('A${_n(h)},${_n(h)} 0 0 1 ${_n(a.$1)},${_n(a.$2 - h)}')
    ..write('Z');
  return d.toString();
}

String _drawable(int viewport, String color, String pathData, {int? size}) {
  final dp = size ?? viewport;
  return '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_android_icons.dart from lib/brand_geometry.dart. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${dp}dp"
    android:height="${dp}dp"
    android:viewportWidth="$viewport"
    android:viewportHeight="$viewport">
    <path
        android:fillColor="$color"
        android:fillType="evenOdd"
        android:pathData="$pathData" />
</vector>
''';
}
